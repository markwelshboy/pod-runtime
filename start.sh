#!/usr/bin/env bash
set -euo pipefail

touch ~/.no_auto_tmux
umask 0022

echo "=== ComfyUI bootstrap: $(date) ==="

#----------------------------------------------
# -2) Capture the environment so we can
#       recreate it in a bash shell
#----------------------------------------------

mkdir -p /workspace

# === Persist session env for later SSH logins ===
SECRET_DIR="/root/.secrets"
SESSION_ENV="${SECRET_DIR}/env.current"

mkdir -p "$SECRET_DIR"
chmod 700 "$SECRET_DIR"
umask 077

# Prefixes to persist (pattern is bash glob)
PERSIST_GLOBS=(
  "ENABLE_*"
  "INSTALL_*"
  "*_TOKEN"
  "HF_*"
  "GIT_*"
  "LAUNCH_*"
  "TELEGRAM_*"
  "*_URL"
  "*_IDS_TO_DOWNLOAD"
)

# Gather candidate variable names from the environment (NUL-separated; safe)
mapfile -d '' -t __env_names < <(env -0 | sed -z 's/=.*//')

# Filter to those matching any desired glob
__persist_names=()
for n in "${__env_names[@]}"; do
  # sanity: only normal bash identifiers
  [[ "$n" =~ ^[A-Za-z_][A-Za-z0-9_]*$ ]] || continue

  for g in "${PERSIST_GLOBS[@]}"; do
    if [[ "$n" == $g ]]; then
      __persist_names+=("$n")
      break
    fi
  done
done

# De-dupe + stable order
IFS=$'\n' __persist_names=($(printf "%s\n" "${__persist_names[@]}" | awk '!seen[$0]++' | sort))
unset IFS

# Write the secret env file
{
  echo "# Autogenerated $(date -Is)"
  for k in "${__persist_names[@]}"; do
    # Only export if set in current shell/env
    if [[ ${!k+set} ]]; then
      v="${!k}"
      [[ -n "$v" ]] && printf 'export %s=%q\n' "$k" "$v"
    fi
  done
} > "$SESSION_ENV"

umask 0022

# Optional: non-secret summary for logs
mkdir -p /workspace/logs
SUMMARY="/workspace/logs/env.summary"

# Anything matching these substrings is treated as secret-ish and omitted
SECRET_NAME_RE='(TOKEN|SECRET|PASSWORD|PASS|KEY|CREDENTIAL|COOKIE|BEARER|AUTH|PRIVATE)'

{
  echo "Generated: $(date -Is)"
  for k in "${__persist_names[@]}"; do
    [[ "$k" =~ $SECRET_NAME_RE ]] && continue
    if [[ -v "$k" ]]; then
      printf '%-32s = %s\n' "$k" "${!k}"
    fi
  done
} > "$SUMMARY"

echo "Saved session env to $SESSION_ENV; summary at $SUMMARY"

#----------------------------------------------
# -1) Wire up .env and helpers
#----------------------------------------------

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
ENVIRONMENT="${ENVIRONMENT:-$SCRIPT_DIR/.env}"
HELPERS="${HELPERS:-$SCRIPT_DIR/helpers.sh}"

if [[ ! -f "$ENVIRONMENT" ]]; then
  echo "[fatal] .env not found at: $ENVIRONMENT" >&2
  exit 1
fi
# shellcheck source=/dev/null
source "$ENVIRONMENT"

if [[ ! -f "$HELPERS" ]]; then
  echo "[fatal] helpers.sh not found at: $HELPERS" >&2
  exit 1
fi
# shellcheck source=/dev/null
source "$HELPERS"

# SSH is a recovery path, not an application service. Bring it up before any
# external network diagnostics or provisioning so a stalled probe cannot lock
# us out of the pod.
echo "[bootstrap] Bringing up SSH recovery access before network qualification..."
setup_ssh || true

# Qualify network performance before package installs, custom nodes, or models.
# The guarded helper has a hard outer wall-clock ceiling and never aborts startup.
network_probe_startup_guarded || true

# Install hf-tools into system
install_system_hff || {
  echo "[fatal] hf-tools installation failed." >&2
  exit 1
}

# Move dotfiles into root home for other SSH connections
install_root_shell_dotfiles || true

# Make sure dirs exist (Comfy home, models, logs, etc.)
ensure_comfy_dirs
link_comfy_state_into_app

#------------------------------------------------------------------------
section 0 "Prepare Session Logging"
#------------------------------------------------------------------------

STARTUP_LOG="${COMFY_LOGS}/startup.log"
exec > >(tee -a "$STARTUP_LOG") 2>&1

echo "[bootstrap] Logging to: ${STARTUP_LOG}"

#------------------------------------------------------------------------
section 0.1 "Start-up Telegram Message"
#------------------------------------------------------------------------

tg "▶️ Starting bootstrap of ComfyUI inference session" || true

#------------------------------------------------------------------------
section 0.5 "Basic Housekeeping"
#------------------------------------------------------------------------

hf_transfer_tune
hf_transfer_install
hf_transfer_verify

#------------------------------------------------------------------------
section 1 "Status/Configuration Overview"
#------------------------------------------------------------------------

on_start_comfy_banner

echo "HF base families : ${HF_BASE_DOWNLOADS:-<none>}"
echo "HF LoRA families : ${HF_LORA_DOWNLOADS:-<none>}"

#------------------------------------------------------------------------
section 2 "SSH Recovery Access"
#------------------------------------------------------------------------

echo "[ssh] SSH was configured during early bootstrap."

#------------------------------------------------------------------------
section 3 "Git Auth Bootstrap"
#------------------------------------------------------------------------

git_auth_bootstrap || true

#------------------------------------------------------------------------
# Explicit one-shot pod snapshot recreation. Normal launches NEVER select a
# leftover snapshot-local manifest. Restore before custom node installation.
#------------------------------------------------------------------------
if [[ -n "${POD_RESTORE_SNAPSHOT:-}" ]]; then
  restore_group="${POD_RESTORE_GROUP:-comfy-workspace}"
  restore_id="${POD_RESTORE_SNAPSHOT}"
  if [[ ! "$restore_group" =~ ^[A-Za-z0-9][A-Za-z0-9_-]{0,63}$ ]]; then
    echo "[snapshot-restore] Invalid POD_RESTORE_GROUP: $restore_group" >&2
    exit 2
  fi
  if [[ ! "$restore_id" =~ ^[A-Za-z0-9_-]+$ ]]; then
    echo "[snapshot-restore] Invalid POD_RESTORE_SNAPSHOT identifier" >&2
    exit 2
  fi

  section 3.5 "Restore ComfyUI Workspace Snapshot"
  echo "[snapshot-restore] Restoring ${restore_group}/${restore_id} before custom-node installation"
  if ! "$SCRIPT_DIR/configure-pod" "$restore_group" --snapshot "$restore_id"; then
    echo "[snapshot-restore] Restore failed; refusing incomplete environment restoration." >&2
    exit 1
  fi
  local_snapshot_manifest="/workspace/.pod-state/custom_nodes/manifest.json"
  local_snapshot_inventory="/workspace/.pod-state/custom_nodes/inventory.json"
  [[ -f "$local_snapshot_manifest" && -f "$local_snapshot_inventory" ]] || {
    echo "[snapshot-restore] No custom-node manifest/inventory in restored snapshot." >&2
    exit 1
  }

  snapshot_python="$(command -v python3 || true)"
  [[ -n "$snapshot_python" ]] || {
    echo "[snapshot-restore] Python 3 unavailable for manifest validation" >&2
    exit 1
  }
  # Validate before overriding launcher configuration. Do not edit the main
  # manifest, and never select a snapshot manifest on ordinary startup.
  if ! restore_sets="$("$snapshot_python" "$SCRIPT_DIR/bin/custom_node_snapshot.py" restore-sets --manifest "$local_snapshot_manifest" --inventory "$local_snapshot_inventory" --launcher-sets "${CUSTOM_NODE_SETS:-}")"; then
    echo "[snapshot-restore] Custom-node manifest validation failed." >&2
    exit 1
  fi
  export CUSTOM_NODES_MANIFEST_URL="$local_snapshot_manifest"
  export CUSTOM_NODE_SETS="$restore_sets"
  echo "[snapshot-restore] Manifest: $CUSTOM_NODES_MANIFEST_URL"
  echo "[snapshot-restore] Sets: default${CUSTOM_NODE_SETS:+,$CUSTOM_NODE_SETS}"
  if [[ "${INSTALL_CUSTOM_NODES:-true}" == "false" ]]; then
    echo "[snapshot-restore] WARN: INSTALL_CUSTOM_NODES=false; nodes will not be installed." >&2
  fi
fi

#------------------------------------------------------------------------
section 4 "Install Custom Nodes"
#------------------------------------------------------------------------
# Keep this phase free of bulk model downloads. Custom-node pip installs are
# latency/I/O sensitive, while the HF/Xet model phase is throughput-oriented.

if [[ "${INSTALL_CUSTOM_NODES:-true}" == "true" ]]; then
  echo "Installing custom nodes. Trying ${CUSTOM_NODES_MANIFEST_URL}..."
  if ! install_custom_nodes; then
    echo "⚠️ install_custom_nodes reported errors; custom-node extras may be incomplete."
  fi
  snapshot_custom_nodes_state "after-install_custom_nodes" || true
else
  echo "INSTALL_CUSTOM_NODES=false → skipping extra custom node installation."
fi

# Built-in Workspace Snapshots frontend/backend bridge. Keep this separate
# from the third-party node manifest; its code ships with pod-runtime.
if [[ "${INSTALL_WORKSPACE_SNAPSHOT_NODE:-true}" == "true" ]]; then
  ws_source="$SCRIPT_DIR/custom_nodes/pod_runtime_workspace_snapshot"
  ws_target="$COMFY_HOME/custom_nodes/pod_runtime_workspace_snapshot"
  if [[ -d "$ws_source" ]]; then
    if [[ -L "$ws_target" ]]; then
      ln -sfn "$ws_source" "$ws_target"
    elif [[ ! -e "$ws_target" ]]; then
      ln -s "$ws_source" "$ws_target"
    else
      echo "[workspace-snapshot] Existing non-symlink node at $ws_target; leaving untouched." >&2
    fi
    echo "[workspace-snapshot] Installed custom node from $ws_source"
  else
    echo "[workspace-snapshot] Source directory missing: $ws_source" >&2
  fi
fi

#------------------------------------------------------------------------
section 5 "SageAttention: Pull (if available) or Build from Source"
#------------------------------------------------------------------------

if [[ "${ENABLE_SAGE:-true}" == "true" ]]; then
  echo "Ensuring SageAttention (bundle or build)..."
  if ! ensure_sage_from_bundle_or_build; then
    echo "⚠️ SageAttention failed; check logs. Continuing without aborting."
  else
    push_sage_bundle_if_requested || true
  fi
else
  echo "ENABLE_SAGE=false → skipping SageAttention setup."
fi

#------------------------------------------------------------------------
section 6 "Hugging Face Base Models"
#------------------------------------------------------------------------
# HF_BASE_DOWNLOADS is a comma/space-separated family list. Each family maps
# directly to <family>_base in model_manifest.json. Base downloads are started
# only after custom-node/Sage setup, then may overlap the lightweight workflow
# sync below.

HF_BASE_STATE="${HF_MANIFEST_STATE_DIR}/base"
HF_LORA_STATE="${HF_MANIFEST_STATE_DIR}/loras"
base_download_started=false

if [[ "${ENABLE_MODEL_MANIFEST_DOWNLOAD:-true}" == "true" ]]; then
  if [[ -n "${HF_BASE_DOWNLOADS:-}" ]]; then
    base_sections="$(hf_manifest_sections_for_families "$MODEL_MANIFEST_URL" "$HF_BASE_DOWNLOADS" base)" || {
      echo "[fatal] Could not resolve HF_BASE_DOWNLOADS='${HF_BASE_DOWNLOADS}'." >&2
      exit 2
    }
    echo "Using model manifest: $MODEL_MANIFEST_URL"
    echo "[models] Base families : ${HF_BASE_DOWNLOADS}"
    echo "[models] Base sections : ${base_sections}"
    if hf_download_from_manifest "$MODEL_MANIFEST_URL" "$HF_BASE_STATE" "$base_sections"; then
      base_download_started=true
    else
      echo "⚠️ Base manifest download failed to start; see logs."
    fi
  else
    echo "[models] HF_BASE_DOWNLOADS is empty; no base model families requested."
  fi
else
  echo "ENABLE_MODEL_MANIFEST_DOWNLOAD=false → skipping manifest model downloads."
fi

#------------------------------------------------------------------------
section 7 "Workflow Repository"
#------------------------------------------------------------------------
# This small setup phase is intentionally allowed to overlap the base model
# downloader once the I/O-sensitive custom-node phase has completed.

if [[ "${ENABLE_MY_WORKFLOWS_DOWNLOAD:-false}" == "true" ]]; then
  init_repo --git --exclude-media "$GIT_MYWORKFLOWS_REPO_ID" "$GIT_MYWORKFLOWS_REPO_LOCAL" || true
  rsync_or_symlink_source_to_destination symlink "$GIT_MYWORKFLOWS_REPO_LOCAL" "/workspace"
  _sync_info "✅ Linking files from $GIT_MYWORKFLOWS_REPO_LOCAL into ComfyUI directories via symlinks..."
  mkdir -p "$COMFY_HOME/user/default/workflows/MyWorkflows"
  ln -sfn $GIT_MYWORKFLOWS_REPO_LOCAL/* "$COMFY_HOME/user/default/workflows/MyWorkflows/"

  _sync_info "Ensuring git auth for MyWorkflows repo for future updates (pull/push)..."
  git_repo_use_deploy_key \
    "$GIT_MYWORKFLOWS_REPO_LOCAL" "$GIT_MYWORKFLOWS_REPO_KEY" "$GIT_MYWORKFLOWS_REPO_ID"
else
  echo "ENABLE_MY_WORKFLOWS_DOWNLOAD=false → skipping MyWorkflows sync."
fi

# Base models are blocking: do not advertise the pod as ready until this phase
# has finished. A failed item is reported loudly, but ComfyUI is still launched
# so the pod remains usable for diagnosis/manual recovery.
if [[ "$base_download_started" == true ]]; then
  echo "[models] Waiting for requested base model families..."
  if hf_download_wait "$HF_BASE_STATE"; then
    echo "[models] Base model families are ready."
  else
    echo "⚠️ One or more base model downloads failed; launching ComfyUI for diagnosis." >&2
    hf_download_show_snapshot "$HF_BASE_STATE" || true
  fi
fi

#------------------------------------------------------------------------
section 8 "ComfyUI"
#------------------------------------------------------------------------

snapshot_custom_nodes_state --summary "before-comfy-launch" || true

section 8.1 "Pre-ComfyUI Launch: Confirming Stack Health"

confirm_stack_health_or_stop || true

if [[ -f /workspace/logs/stack_broken ]]; then
  echo "⚠️ Stack broken; NOT launching ComfyUI."
  echo "    You can SSH in and inspect /workspace/logs/stack_health_report.txt"
  tail -f /dev/null
fi

section 8.2 "ComfyUI Launch..."

cd "${COMFY_APP:-/opt/ComfyUI}"

echo ""
echo "▶️  Starting ComfyUI"
echo ""

show_env || true

# The mux reports a bitmask of ports that actually passed their HTTP health
# checks. Capture that line without buffering its live startup output, so the
# Telegram message never advertises an optional GPU port that failed to start.
comfy_telegram_ready_message() {
  local mask="${1:-}" pod_id="${RUNPOD_POD_ID:-}"
  local -a ports=(8188 8288 8388 8488 8588)
  local -a names=("Main" "GPU0" "GPU1" "GPU2" "GPU3")
  local i port url
  local message="🚀 ComfyUI is UP."

  if [[ ! "$mask" =~ ^0x[[:xdigit:]]+$ ]]; then
    printf '%s\n' "$message"
    return 0
  fi

  # SSH-launched sessions may not inherit the RunPod identity. Follow the
  # existing mux behavior and recover only the non-secret ID from PID 1.
  if [[ -z "$pod_id" && -r /proc/1/environ ]]; then
    pod_id="$(tr '\0' '\n' < /proc/1/environ | awk -F= '$1 == "RUNPOD_POD_ID" {print $2; exit}')" || true
  fi
  if [[ ! "$pod_id" =~ ^[A-Za-z0-9-]+$ ]]; then
    printf '%s\n' "$message"
    return 0
  fi

  for i in "${!ports[@]}"; do
    (( (mask & (1 << i)) != 0 )) || continue
    port="${ports[i]}"
    url="https://${pod_id}-${port}.proxy.runpod.net"
    message+=$'\n\n'"${names[i]} (:${port})"
    message+=$'\n'"ComfyUI: ${url}/"
    message+=$'\n'"Mobile:  ${url}/mobile"
  done
  printf '%s\n' "$message"
}

comfy_mux_start_log="$(mktemp)"
if "${SCRIPT_DIR}/run_comfy_mux.sh" start | tee "$comfy_mux_start_log"; then
  comfy_start_mask="$(sed -nE 's/^COMFY_START_MASK=(0x[[:xdigit:]]+) .*/\1/p' "$comfy_mux_start_log" | tail -n 1)"
  tg "$(comfy_telegram_ready_message "$comfy_start_mask")" || true
else
  tg "⚠️ ComfyUI launch had warnings. Check ${COMFY_LOGS}." || true
fi
rm -f "$comfy_mux_start_log"

#------------------------------------------------------------------------
section 9 "Optional Hugging Face LoRAs"
#------------------------------------------------------------------------
# HF_LORA_DOWNLOADS maps each family to <family>_loras. These are deliberately
# non-blocking and begin only after ComfyUI is up, so optional libraries do not
# delay time-to-ready.

if [[ "${ENABLE_MODEL_MANIFEST_DOWNLOAD:-true}" == "true" && -n "${HF_LORA_DOWNLOADS:-}" ]]; then
  lora_sections="$(hf_manifest_sections_for_families "$MODEL_MANIFEST_URL" "$HF_LORA_DOWNLOADS" loras)" || {
    echo "⚠️ Could not resolve HF_LORA_DOWNLOADS='${HF_LORA_DOWNLOADS}'; optional LoRAs will not be downloaded." >&2
    lora_sections=""
  }
  if [[ -n "$lora_sections" ]]; then
    echo "[loras] Families : ${HF_LORA_DOWNLOADS}"
    echo "[loras] Sections : ${lora_sections}"
    if hf_download_from_manifest "$MODEL_MANIFEST_URL" "$HF_LORA_STATE" "$lora_sections"; then
      echo "[loras] Optional LoRA provisioning is running in the background."
      hf_download_show_snapshot "$HF_LORA_STATE" || true
    else
      echo "⚠️ Optional LoRA downloader failed to start." >&2
    fi
  fi
else
  echo "[loras] No optional LoRA families requested."
fi

#------------------------------------------------------------------------
section 10 "Pull my model repo from Hugging Face and symlink into ComfyUI"
#------------------------------------------------------------------------

if [[ "${ENABLE_MY_REPO_DOWNLOAD:-false}" == "true" ]]; then
  export HF_EXCLUDE_GLOBS="${HF_MY_REPO_EXCLUDE_GLOBS:-training/** snapshot/** models/loras/** deleteme/** latestimages/**}"
  export HF_INCLUDE_GLOBS="${HF_MY_REPO_INCLUDE_GLOBS:-models/ultralytics/** models/upscale_models/** models/sam3/**}"

  if HF_REPO_TYPE="${HF_MY_REPO_TYPE:-model}" \
      init_repo --hf "$HF_MY_REPO_ID" "$HF_MY_REPO_LOCAL"; then
    if ! hf_my_repo_sync_assets "$HF_MY_REPO_LOCAL" "$HF_MY_REPO_ID"; then
      _sync_warn "$HF_MY_REPO_ID downloaded, but asset extraction/linking reported errors."
    fi
  else
    _sync_warn "HF repo download failed for $HF_MY_REPO_ID at '$HF_MY_REPO_LOCAL'."
  fi
else
  echo "ENABLE_MYREPO_DOWNLOAD=false → skipping MyRepo sync."
fi

#------------------------------------------------------------------------
section 11 "Disk Watcher"
#------------------------------------------------------------------------

disk_watch_start --path / --log /workspace/logs/disk_watch.log || true
pod_nag --interval 3600 || true

echo ""
echo "Bootstrap complete. Bootstrap log: ${COMFY_LOGS}/startup.log"
echo "General logs: ${COMFY_LOGS}"
echo ""
echo "=== Bootstrap done: $(date) ==="

sleep infinity
